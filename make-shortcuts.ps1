# НАЗНАЧЕНИЕ ЭТОГО СКРИПТА — Собрать значок приложения и оба ярлыка запуска.
#
# ЗАЧЕМ СКРИПТ, А НЕ ГОТОВЫЙ ФАЙЛ ЯРЛЫКА. Ярлык — двоичный файл с абсолютными
# путями ОДНОЙ машины. Переехала папка, сменилась буква диска, обновился
# интерпретатор — ярлык молча ведёт в никуда, а чинится только мышью через
# свойства. В истории репозитория он бесполезен вдвойне: правка не читается,
# слияние не разрешается. Поэтому первоисточник — этот скрипт, а сами ярлыки
# лежат в .gitignore.
#
# ЗНАЧОК ТОЖЕ СОБИРАЕТСЯ ЗДЕСЬ, А НЕ ЛЕЖИТ ФАЙЛОМ. Канон требует одного рисунка
# и одного цвета на трей, шапку окна, панель задач и оба ярлыка. Пока .ico лежал
# отдельным файлом, а трей рисовал свой значок символом, рисунков было два —
# и они расходились молча при любой правке одного из них.
#
# Запуск:  powershell -ExecutionPolicy Bypass -File make-shortcuts.ps1

$ErrorActionPreference = 'Stop'
try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch { }

$Root = $PSScriptRoot
. (Join-Path $Root 'app-window.ps1')

$ИмяЯрлыка = 'Общая клавиатура и мышь'
$ФайлЗначка = Join-Path $Root 'SteamDeck-KVM.ico'
$Запускатель = Join-Path $Root 'SteamDeck-KVM.vbs'

# ==== Значок ==================================================================
# Сборка живёт в app-window.ps1 — там же, где её читает само приложение. Копия
# здесь означала бы два рисунка, расходящихся на первой правке одного из них.
Собрать-Ico $ФайлЗначка
"Значок собран: $ФайлЗначка ($((Get-Item $ФайлЗначка).Length) байт, 4 размера)"

# ==== Ярлыки ==================================================================
# Оба ведут в один и тот же запускатель и берут ОДИН файл значка — иначе одно
# приложение выглядит двумя.
$shell = New-Object -ComObject WScript.Shell
$пути = @(
    (Join-Path $Root "$ИмяЯрлыка.lnk"),
    (Join-Path ([Environment]::GetFolderPath('Desktop')) "$ИмяЯрлыка.lnk")
)

$собрано = 0
foreach ($путь in $пути) {
    $ярлык = $shell.CreateShortcut($путь)
    $ярлык.TargetPath = 'C:\Windows\System32\wscript.exe'
    $ярлык.Arguments = '"' + $Запускатель + '"'
    $ярлык.WorkingDirectory = $Root
    $ярлык.IconLocation = "$ФайлЗначка,0"
    $ярлык.Description = 'Общая клавиатура и мышь со Steam Deck'
    $ярлык.Save()
    $собрано++
    "Ярлык собран: $путь"
}

# ==== Приёмка =================================================================
$верных = 0
foreach ($путь in $пути) {
    $ярлык = $shell.CreateShortcut($путь)
    $целоУказывает = $ярлык.Arguments -like "*$([IO.Path]::GetFileName($Запускатель))*"
    $значокТот = $ярлык.IconLocation -like "$ФайлЗначка*"
    if ((Test-Path $путь) -and $целоУказывает -and $значокТот) { $верных++ }
}
"Приёмка: сверено $собрано, верных $верных"
if ($верных -ne $собрано) { exit 1 }

# Старые имена убираются здесь же: два ярлыка на одно приложение читаются как
# два приложения, а забытый ярлык ведёт в удалённый файл.
$устаревшие = @(
    (Join-Path ([Environment]::GetFolderPath('Desktop')) 'SteamDeck-KVM.lnk')
)
foreach ($путь in $устаревшие) {
    if (Test-Path $путь) { Remove-Item $путь -Force; "Убран устаревший ярлык: $путь" }
}
