# НАЗНАЧЕНИЕ ЭТОГО СКРИПТА — Сторож компоновки окна: ничто не вылезает за край
# и ничто не лежит поверх соседа.
#
# ЗАЧЕМ. WinForms обрезает контрол, вылезший за край родителя, МОЛЧА: ни
# исключения, ни записи в журнал — часть содержимого просто перестаёт
# существовать для глаза. Надпись, добавленная раньше, рисуется ПОВЕРХ
# добавленной позже, и у нижней срезаются верхушки букв — «Работает» читается
# как «Раоотает». Ни то, ни другое не видно в коде.
#
# Сторож НЕ открывает окно: форма собирается в памяти ради настоящих размеров
# (они зависят от рамки, заголовка и системного масштаба, числом их не
# подставить) и сразу освобождается. На экране ничего не появляется.
#
# ПРЕДМЕТ — та же функция New-AppWindow, которую зовёт приложение. Повторить
# числа раскладки здесь значило бы проверять вчерашнее окно, ничего об этом
# не сказав.
#
# Запуск:  powershell -ExecutionPolicy Bypass -File check-window-layout.ps1

$ErrorActionPreference = 'Stop'
try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch { }

# Оболочка лежит в приложении ПК; сторож проверяет ТОТ ЖЕ файл, а не свою копию чисел.
. (Join-Path $PSScriptRoot '..\..\apps\pc\app-window.ps1')

# Худшие случаи текста: самая длинная строка, какая может встать в каждое поле.
# Раскладка обязана держать их, а не ту строку, что написана сегодня.
$ХудшиеСтроки = @{
    Состояние = 'Работает — Deck подключён'
    Подсказка = 'Включите Steam Deck: он найдёт этот компьютер сам, в том числе в игровом режиме.'
    Тумблер   = 'Выключить'
    Факты     = @{
        'Steam Deck'     = 'steamdeck-1234567890 · знаком, сейчас не отвечает'
        'Этот компьютер' = 'DESKTOP-ABCDEFGH · 192.168.100.100'
        'Переход'        = 'край экрана · Ctrl+Alt+→ и Ctrl+Alt+←'
        'Версия'         = '10.20.30 · рабочая копия'
    }
}

$Ширины = @(520, 560, 600, 720)

$нарушений = 0
$проверено = 0

function Сказать-Нарушение([string]$текст) {
    $script:нарушений++
    Write-Host "  НАРУШЕНИЕ: $текст" -ForegroundColor Red
}

foreach ($ширина in $Ширины) {
    Write-Host "Ширина $ширина"
    $ui = New-AppWindow -Ширина $ширина
    $форма = $ui.Форма
    try {
        # Текст ставится ХУДШИЙ: короткая строка прячет дефект, а не лечит его.
        $ui.Состояние.Text = $ХудшиеСтроки.Состояние
        $ui.Подсказка.Text = $ХудшиеСтроки.Подсказка
        $ui.Тумблер.Text = $ХудшиеСтроки.Тумблер
        foreach ($ключ in $ХудшиеСтроки.Факты.Keys) { $ui.Факты[$ключ].Text = $ХудшиеСтроки.Факты[$ключ] }

        $g = $форма.CreateGraphics()

        # 1. Ничто не выходит за низ и за правый край своего родителя.
        function Проверить-Границы($родитель, [string]$имяРодителя) {
            foreach ($контрол in $родитель.Controls) {
                # Полоса обновления живёт за нижним краем, пока не показана, — это её место по
                # замыслу; её границы проверяет отдельный шаг 10 в показанном состоянии.
                if ($контрол -eq $ui.Обновление -and -not $script:полосаПоказана) { continue }
                $script:проверено++
                if ($контрол.Bottom -gt $родитель.ClientSize.Height) {
                    Сказать-Нарушение ("«{0}» уходит за низ {1} на {2} точек" -f $контрол.Text, $имяРодителя, ($контрол.Bottom - $родитель.ClientSize.Height))
                }
                if ($контрол.Right -gt $родитель.ClientSize.Width) {
                    Сказать-Нарушение ("«{0}» уходит за правый край {1} на {2} точек" -f $контрол.Text, $имяРодителя, ($контрол.Right - $родитель.ClientSize.Width))
                }
                if ($контрол.Controls.Count -gt 0) { Проверить-Границы $контрол ("«" + $контрол.Name + "»") }
            }
        }
        $script:полосаПоказана = $false
        Проверить-Границы $форма 'окна'
        Проверить-Границы $ui.Карточка 'карточки состояния'

        # 2. Надписи не лежат друг на друге: верхняя рисуется поверх нижней, и
        #    у нижней срезаются верхушки букв — в коде это не видно вовсе.
        $поля = @($форма.Controls | Where-Object { $_ -is [System.Windows.Forms.Label] -or $_ -is [System.Windows.Forms.Button] })
        for ($i = 0; $i -lt $поля.Count; $i++) {
            for ($j = $i + 1; $j -lt $поля.Count; $j++) {
                $script:проверено++
                if ($поля[$i].Bounds.IntersectsWith($поля[$j].Bounds)) {
                    Сказать-Нарушение ("«{0}» и «{1}» накладываются" -f $поля[$i].Text, $поля[$j].Text)
                }
            }
        }

        # 3. Текст помещается в отведённое поле: обрезанная надпись — тот же
        #    молчаливый дефект, только внутри контрола, а не за его краем.
        $измеряемые = @($ui.Состояние, $ui.Подсказка, $ui.Тумблер) + @($ui.Факты.Values) + @($ui.Кнопки.Values)
        foreach ($поле in $измеряемые) {
            $script:проверено++
            # Поле с многоточием меряется ОДНОЙ строкой: обрез там объявлен и
            # виден человеку. Остальные меряются с переносом — у них обрез молчит.
            $однострочное = ($поле -is [System.Windows.Forms.Label]) -and $поле.AutoEllipsis
            $размер = if ($однострочное) { $g.MeasureString($поле.Text, $поле.Font) }
                      else { $g.MeasureString($поле.Text, $поле.Font, $поле.Width) }
            if ([Math]::Ceiling($размер.Height) -gt $поле.Height) {
                Сказать-Нарушение ("«{0}» не помещается по высоте: нужно {1}, отведено {2}" -f $поле.Text, [int][Math]::Ceiling($размер.Height), $поле.Height)
            }
        }

        # 4. Подпись кнопки помещается в ОДНУ строку. Перенос кнопка допускает
        #    молча, и высоты ей хватает — поэтому проверка по высоте этот дефект
        #    пропускает: «Как настроить Deck» ложилось двумя строками, а сторож
        #    молчал. Кнопка с переносом читается как тесная и недоделанная.
        foreach ($кнопка in @($ui.Кнопки.Values) + @($ui.Тумблер)) {
            $script:проверено++
            $однаСтрока = $g.MeasureString($кнопка.Text, $кнопка.Font)
            if ([Math]::Ceiling($однаСтрока.Width) -gt ($кнопка.Width - 10)) {
                Сказать-Нарушение ("подпись кнопки «{0}» не помещается в строку: нужно {1}, есть {2}" -f $кнопка.Text, [int][Math]::Ceiling($однаСтрока.Width), ($кнопка.Width - 10))
            }
        }

        # 5. Состав кнопок окна — тот, на который рассчитано приложение.
        #    Переименование подписи в оболочке тихо разрывает связь с обработчиком:
        #    кнопка остаётся на месте и перестаёт что-либо делать. Перечень здесь
        #    нарочно дублирует оболочку — расхождение и есть сигнал.
        $script:проверено++
        $ожидаемые = @('Настроить Deck', 'Забыть Deck', 'Журнал')
        $лишние = @($ui.Кнопки.Keys | Where-Object { $ожидаемые -notcontains $_ })
        $пропавшие = @($ожидаемые | Where-Object { -not $ui.Кнопки.ContainsKey($_) })
        if ($лишние.Count -or $пропавшие.Count) {
            Сказать-Нарушение ("состав кнопок разошёлся: лишние [{0}], пропавшие [{1}]" -f ($лишние -join ', '), ($пропавшие -join ', '))
        }

        # 6. Значок ОДИН на все места. Шапка окна, панель задач, трей и оба
        #    ярлыка обязаны брать один и тот же файл: рисунок, собранный в
        #    памяти для одного места и прочитанный из файла для другого, — это
        #    два значка, и человек видит два приложения. Замер 12.09.2026:
        #    в трее и шапке стоял ⇄ из памяти, в панели задач — растянутый
        #    однокадровый, в ярлыке — третий из старого файла.
        $script:проверено++
        if (-not (Test-Path $script:IconPath)) {
            Сказать-Нарушение "нет файла значка $($script:IconPath) — панели задач брать нечего"
        } else {
            $изФайла = New-Object System.Drawing.Icon($script:IconPath)
            $сниматьБайты = {
                param($значок)
                $b = $значок.ToBitmap()
                $поток = New-Object System.IO.MemoryStream
                $b.Save($поток, [System.Drawing.Imaging.ImageFormat]::Png)
                $итог = [Convert]::ToBase64String($поток.ToArray())
                $поток.Dispose(); $b.Dispose()
                return $итог
            }
            $script:проверено++
            if ((& $сниматьБайты $форма.Icon) -ne (& $сниматьБайты $изФайла)) {
                Сказать-Нарушение 'значок окна не равен значку из файла: шапка и панель задач разойдутся'
            }
            $script:проверено++
            # Кадров обязано быть четыре: 16 — шапка, 32 и 48 — панель задач,
            # 256 — проводник. Однокадровый .ico Windows растягивает сама.
            $кадров = [BitConverter]::ToUInt16([IO.File]::ReadAllBytes($script:IconPath)[4..5], 0)
            if ($кадров -lt 4) {
                Сказать-Нарушение "в значке $кадров кадр(ов) вместо четырёх: панель задач получит растянутый"
            }
            $изФайла.Dispose()
        }

        # 7. Значения берутся из контракта, а не из запаса: подмена молча вернула
        #    бы вид по умолчанию Windows, ради которого сторож и заведён.
        $script:проверено++
        if ($ui.Тумблер.Font.Name -ne $script:FontName -and $script:FontName -ne 'Segoe UI') {
            Сказать-Нарушение ("гарнитура тумблера «{0}» не равна контрактной «{1}»" -f $ui.Тумблер.Font.Name, $script:FontName)
        }
        $script:проверено++
        if ($null -eq $ui.Карточка.Region) {
            Сказать-Нарушение 'карточка состояния без скругления: радиус из контракта не применён'
        }

        # 10. Полоса обновления: показанная, влезает в окно и не налезает на подвал; скрытая —
        #     окно возвращается к прежней высоте, а не остаётся раздутым.
        $высотаДо = $форма.ClientSize.Height
        Показать-Обновление $ui ('Обновить до 10.20.30 — ' + ('очень длинная первая строка заметки выпуска ' * 3))
        $script:полосаПоказана = $true
        $script:проверено++
        if ($ui.Обновление.Bottom -gt $форма.ClientSize.Height) {
            Сказать-Нарушение ("полоса обновления уходит за низ окна на {0} точек" -f ($ui.Обновление.Bottom - $форма.ClientSize.Height))
        }
        $script:проверено++
        if ($ui.Обновление.Top -lt $ui.Подвал.Bottom) {
            Сказать-Нарушение 'полоса обновления налезает на подвал'
        }
        Показать-Обновление $ui 'повторный показ'
        $высотаПослеДвух = $форма.ClientSize.Height
        Скрыть-Обновление $ui
        $script:проверено++
        if ($форма.ClientSize.Height -ne $высотаДо) {
            Сказать-Нарушение ("скрытая полоса не вернула высоту окна: было {0}, стало {1}" -f $высотаДо, $форма.ClientSize.Height)
        }
        $script:проверено++
        if ($высотаПослеДвух -ne ($ui.Высоты.С)) {
            Сказать-Нарушение 'повторный показ полосы вырастил окно второй раз'
        }
        $script:полосаПоказана = $false

        $g.Dispose()
    } finally {
        $форма.Dispose()
    }
}

# 8. Панель задач берёт значок по ИМЕНИ ПРИЛОЖЕНИЯ, а не по значку окна.
#    Без своего имени Windows подставляет имя процесса — powershell.exe — и его
#    синий значок: замер 12.09.2026, в шапке окна стоял ⇄, в панели задач чужой
#    квадрат. Смена значка окна этого не лечит, поэтому проверка отдельная.
$проверено++
Add-Type -Namespace Сторож -Name Ид -MemberDefinition @'
[DllImport("shell32.dll")] public static extern int GetCurrentProcessExplicitAppUserModelID(out System.IntPtr id);
'@ -ErrorAction SilentlyContinue
try {
    $указатель = [IntPtr]::Zero
    $код = [Сторож.Ид]::GetCurrentProcessExplicitAppUserModelID([ref]$указатель)
    if ($код -ne 0) {
        Сказать-Нарушение 'имя приложения не установлено: панель задач возьмёт значок интерпретатора'
    } else {
        $имя = [System.Runtime.InteropServices.Marshal]::PtrToStringUni($указатель)
        if (-not $имя) {
            Сказать-Нарушение 'имя приложения пустое: панель задач возьмёт значок интерпретатора'
        } else {
            Write-Host "  имя приложения: $имя"
        }
    }
} catch {
    Сказать-Нарушение ('имя приложения не проверить: ' + $_.Exception.Message)
}

# 9. ПЛАШКА по правой кнопке на значке: ни одна строка не обрезана шапкой, ни один
#    пункт не вылез за плашку, шапка и пункты не наложились.
#
#    Прежде правая кнопка поднимала системное меню Windows, и проверять было
#    нечего — раскладку делала система. Своя плашка эту работу забрала, а вместе с
#    ней и этот класс дефектов: замер 12.09.2026 на соседнем приложении
#    — шапке задали высоту числом, четвёртая строка вылезла на четыре точки, и
#    WinForms обрезал её молча. На снимке экрана строка читалась как перечёркнутая.
#
#    Плашка собирается в памяти и уводится за пределы экрана: на экране ничего не
#    появляется. Текст берётся ХУДШИЙ — самая длинная строка состояния.
foreach ($случай in @(
    @{ Состояние = 'Работает — Deck подключён'; Тумблер = 'Выключить' },
    @{ Состояние = 'Включено — ждём Deck';      Тумблер = 'Включить' },
    @{ Состояние = 'Выключено';                 Тумблер = 'Включить' },
    @{ Состояние = ('Работает — Deck подключён, ' + ('очень длинное имя устройства ' * 3));
       Тумблер = 'Выключить' }
)) {
    $проверено++
    $п = Новая-Плашка -Состояние $случай.Состояние -ЦветСостояния $C_OK `
                      -ТекстТумблера $случай.Тумблер -ЦветТумблера $C_ACCENT
    $пл = $п.Форма
    try {
        $пл.StartPosition = 'Manual'
        $пл.Location = New-Object System.Drawing.Point(-6000, -6000)
        $пл.ShowInTaskbar = $false
        foreach ($н in $п.Надписи) {
            if (($н.Bottom) -gt $п.Шапка.ClientSize.Height) {
                Сказать-Нарушение ("плашка: строка «{0}» обрезана шапкой — низ {1} при высоте шапки {2}" -f
                                   $н.Text, $н.Bottom, $п.Шапка.ClientSize.Height)
            }
        }
        foreach ($пункт in @($п.Тумблер, $п.Выход)) {
            if ($пункт.Bottom -gt $пл.ClientSize.Height -or $пункт.Right -gt $пл.ClientSize.Width) {
                Сказать-Нарушение ("плашка: пункт «{0}» вылез за край — низ {1}, право {2}, плашка {3}x{4}" -f
                                   $пункт.Text, $пункт.Bottom, $пункт.Right,
                                   $пл.ClientSize.Width, $пл.ClientSize.Height)
            }
        }
        if ($п.Тумблер.Top -lt $п.Шапка.Bottom) {
            Сказать-Нарушение ("плашка: пункт начинается на {0}, а шапка кончается на {1}" -f
                               $п.Тумблер.Top, $п.Шапка.Bottom)
        }
        if ($п.Выход.Top -lt $п.Тумблер.Bottom) {
            Сказать-Нарушение ("плашка: «Закрыть» налезает на тумблер" )
        }
        # Плашка обязана быть скруглена радиусом карточки из контракта: прямоугольная
        # плашка рядом со скруглённым окном читается как чужое приложение.
        if ($null -eq $пл.Region) {
            Сказать-Нарушение 'плашка не скруглена радиусом из контракта палитры'
        }
    } finally { $пл.Dispose() }
}

Write-Host ''
Write-Host ("Проверено размеров окна: {0}; проверок: {1}; нарушений: {2}" -f $Ширины.Count, $проверено, $нарушений)
if ($нарушений -gt 0) { exit 1 }
Write-Host 'Компоновка чиста.' -ForegroundColor Green
