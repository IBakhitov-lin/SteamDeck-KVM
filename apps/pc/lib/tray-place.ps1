# КОПИЯ общего модуля, собранная build_release_script.py из общего канона автора.
# Правится исходник, а не копия: копия перезаписывается при каждой сборке выпуска.
# НАЗНАЧЕНИЕ ЭТОГО СКРИПТА — Общая механика места плашки трея: одна на все приложения с значком
#
# Область: любое своё приложение со значком в трее и своей плашкой по правой кнопке.
# Потребители на 12.09.2026 — соседний проект (`private_tools\scripts\соседний проект_tray.ps1`),
# DeepSeek Harness (`.launcher\tray.ps1`), SteamDeck-KVM (`SteamDeck-KVM.ps1`).
#
# ПОЧЕМУ ОБЩИЙ ФАЙЛ. Механика вынесена по правилу «общее выносится при ВТОРОМ
# потребителе, не при третьем» (`C:\AI\workflow.md`, «Своё, чужое и открытое»).
# Здесь потребителей три, и каждый ошибался ОДИНАКОВО: считал место плашки одним
# числом — углом экрана, — и на панели задач сверху или сбоку плашка появлялась в
# другом конце экрана, а на втором мониторе не на том, где нажали. Три копии
# правила давали три разных ошибки одного вида; правило одно, и жить ему в одном
# месте.
#
# Правило целиком — `C:\AI\app_canon.md`, раздел «Трей».
#
# ПОДКЛЮЧЕНИЕ. Файл предназначен для чтения точкой:
#     . 'C:\AI\scripts\tray-place.ps1'
# Приложение обязано пережить его отсутствие: канон требует запаса у всего, что
# берётся из общего места. Образец запасного хода — у потребителей.
#
# Функции ЧИСТЫЕ: получают прямоугольники числами и возвращают точку. Ни окна, ни
# экрана, ни панели задач им не нужно — ровно поэтому их проверяет
# `tray-place.tests.ps1` на всех раскладках, включая те, которых на этой машине нет.

function Край-Панели-Задач($рабочая, $границы) {
    <#
      С какой стороны экрана стоит панель задач. Ответ читается из РАЗНИЦЫ между
      полными границами экрана и рабочей областью: панель задач — единственное,
      что рабочую область урезает, и Windows вычитает её сам.

      Возвращает 'низ', 'верх', 'слева', 'справа' либо 'нет' — последнее, когда
      панель спрятана автоматически или экран занят полноэкранным окном. Тогда
      привязываться не к чему, и плашка встаёт просто у курсора.
    #>
    $снизу = $границы.Bottom - $рабочая.Bottom
    $сверху = $рабочая.Top - $границы.Top
    $слева = $рабочая.Left - $границы.Left
    $справа = $границы.Right - $рабочая.Right
    $наибольший = [Math]::Max([Math]::Max($снизу, $сверху), [Math]::Max($слева, $справа))
    if ($наибольший -lt 2) { return 'нет' }
    if ($наибольший -eq $снизу)  { return 'низ' }
    if ($наибольший -eq $сверху) { return 'верх' }
    if ($наибольший -eq $слева)  { return 'слева' }
    return 'справа'
}

function Место-Плашки([int]$ш, [int]$в, $курсор, $рабочая, $границы) {
    <#
      Где встать плашке, вызванной правой кнопкой по значку в трее.

      Правило то же, по которому Windows раскрывает свои меню у значков, и оно
      состоит из двух независимых решений.

      ПРИВЯЗКА — к панели задач. Плашка прижимается к рабочей области с той
      стороны, где панель стоит: значок живёт в панели, и всплывшее от него
      обязано выходить из неё, а не появляться поодаль.

      НАПРАВЛЕНИЕ — от курсора в ту сторону, где есть место. Значок в правом
      углу раскрывает плашку ВЛЕВО, в левом — вправо; иначе она упирается в край
      и её отодвигает обратно, а человек видит плашку не там, куда нажал.
    #>
    $зазор = 8
    $край = Край-Панели-Задач $рабочая $границы

    # Раскрытие вправо — когда справа от курсора помещается вся плашка.
    $вправо = ($курсор.X + $зазор + $ш) -le $рабочая.Right
    # Раскрытие вниз — то же самое по вертикали.
    $вниз = ($курсор.Y + $зазор + $в) -le $рабочая.Bottom

    switch ($край) {
        'низ'    { $y = $рабочая.Bottom - $в - $зазор; if ($вправо) { $x = $курсор.X } else { $x = $курсор.X - $ш } }
        'верх'   { $y = $рабочая.Top + $зазор;         if ($вправо) { $x = $курсор.X } else { $x = $курсор.X - $ш } }
        'слева'  { $x = $рабочая.Left + $зазор;        if ($вниз)   { $y = $курсор.Y } else { $y = $курсор.Y - $в } }
        'справа' { $x = $рабочая.Right - $ш - $зазор;  if ($вниз)   { $y = $курсор.Y } else { $y = $курсор.Y - $в } }
        default  {
            if ($вправо) { $x = $курсор.X + $зазор } else { $x = $курсор.X - $ш - $зазор }
            if ($вниз)   { $y = $курсор.Y + $зазор } else { $y = $курсор.Y - $в - $зазор }
        }
    }

    # Прижатие к рабочей области — последним делом и по обеим осям. Оно чинит
    # случай, которого правила выше не покрывают: плашка выше или шире того, что
    # осталось на экране.
    $x = [Math]::Min($x, $рабочая.Right - $ш - $зазор)
    $x = [Math]::Max($x, $рабочая.Left + $зазор)
    $y = [Math]::Min($y, $рабочая.Bottom - $в - $зазор)
    $y = [Math]::Max($y, $рабочая.Top + $зазор)
    return (New-Object System.Drawing.Point([int]$x, [int]$y))
}

function Высота-Строки-Плашки([double]$кегль) {
    <# Высота надписи по кеглю. ОДНА формула на приложение: у фабрики надписей и
       у счёта раскладки она обязана быть одна и та же, иначе строка рисуется
       выше, чем под неё отвели, и её низ обрезается МОЛЧА — ни исключения, ни
       записи в журнал. Замер 12.09.2026 на плашке соседний проект: шапке задали высоту
       100 числом, четвёртая строка встала на 80-ю точку высотой 25 и вылезла на
       четыре точки; на снимке экрана «Обход сайтов» читалось как перечёркнутое. #>
    return [int]($кегль * 2.2) + 6
}

function Раскладка-Плашки($строки, [int]$поле, [int]$зазорСтрок,
                          [int]$зазорДоКнопок, [int]$высотаКнопки, [int]$подвал,
                          [int]$пунктов = 2) {
    <#
      Числа раскладки плашки: где стоит каждая строка шапки, где начинается ряд
      пунктов и какой высоты сама плашка.

      Строки идут КУРСОРОМ: каждая следующая от низа предыдущей. Добавить строку
      значит дописать пункт в перечень, а не пересчитать четыре числа. Число в
      раскладке — не «пока так», а отложенный дефект: оно верно ровно для того
      набора строк, который был написан в день его подбора.

      `$строки` — перечень таблиц с полем `Кегль`; функция дописывает в каждую
      `Y` и `Высота`. `$пунктов` — сколько РЯДОВ пунктов идёт под шапкой.

      Возвращает: ВысотаШапки, ВерхРяда (первый ряд пунктов), Ряды (верх каждого
      ряда) и Высота (всей плашки).
    #>
    $курсор = $поле
    foreach ($с in $строки) {
        $с['Высота'] = Высота-Строки-Плашки $с.Кегль
        $с['Y'] = $курсор
        $курсор += $с.Высота + $зазорСтрок
    }
    # Последний зазор не нужен: под нижней строкой стоит поле, а не строка.
    $высотаШапки = $курсор - $зазорСтрок + $поле
    $ряды = @()
    $верх = $высотаШапки + $зазорДоКнопок
    for ($i = 0; $i -lt [Math]::Max(1, $пунктов); $i++) {
        $ряды += $верх
        $верх += $высотаКнопки + 6
    }
    return @{
        ВысотаШапки = $высотаШапки
        ВерхРяда    = $ряды[0]
        Ряды        = $ряды
        Высота      = $верх - 6 + $подвал
    }
}
