# НАЗНАЧЕНИЕ ЭТОГО МОДУЛЯ — Обновление приложения ПК из выпусков GitHub: выбор выпуска, сверка суммы, раскладка файлов
#
# ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ — приложение держит окно и сервер, и проверить в нём обновление можно
# было бы только живым запуском, который трогает работающий сервер и ярлык на рабочем столе.
# Здесь только решения без окна и без сети: какой выпуск взять, сошлась ли сумма, как разложить
# файлы. Их проверяет tests\apps\test_pc_app_update.py в памяти. Загрузку и очередность шагов
# ведёт само приложение — там, где у него таймер.
#
# ЧЕГО СВЕРКА СУММЫ НЕ ДОКАЗЫВАЕТ — она ловит оборванную и испорченную загрузку; от подмены
# выпуска владельцем учётной записи не защищает: сумма лежит в том же выпуске.

function Разобрать-Версию([string]$Текст) {
    if ($Текст -match '^v?(\d+)\.(\d+)\.(\d+)') {
        return [version]("{0}.{1}.{2}" -f $Matches[1], $Matches[2], $Matches[3])
    }
    return $null
}

function Выбрать-Обновление($Выпуск, [string]$ТекущаяВерсия) {
    <#
      Выпуск новее текущей версии с архивом для ПК и контрольными суммами — либо $null.
      Причина пропуска возвращается полем, а не пишется в журнал отсюда: журнал ведёт приложение.
    #>
    $новая = Разобрать-Версию $Выпуск.tag_name
    $текущая = Разобрать-Версию $ТекущаяВерсия
    if (-not $новая -or -not $текущая -or $новая -le $текущая) { return $null }
    $архив = @($Выпуск.assets | Where-Object { $_.name -like 'SteamDeck-KVM-*-windows-x64.zip' })[0]
    $суммы = @($Выпуск.assets | Where-Object { $_.name -eq 'SHA256SUMS.txt' })[0]
    if (-not $архив -or -not $суммы) {
        return @{ Пропуск = ("выпуск {0} без архива для ПК или без контрольных сумм" -f $Выпуск.tag_name) }
    }
    $заметка = @(($Выпуск.body -split "`n") | Where-Object { $_.Trim() })[0]
    $заметка = if ($заметка) { $заметка.Trim().TrimStart('#', '-', ' ').Trim() } else { '' }
    return @{ Версия = "$новая"; Архив = $архив; Суммы = $суммы; Заметка = $заметка }
}

function Ожидаемая-Сумма([string]$ТекстСумм, [string]$ИмяФайла) {
    foreach ($строка in ($ТекстСумм -split "`n")) {
        $части = $строка.Trim() -split '\s+'
        if ($части.Count -eq 2 -and $части[1].TrimStart('*') -eq $ИмяФайла) { return $части[0].ToUpperInvariant() }
    }
    return $null
}

function Разложить-Обновление {
    <#
      Проверить архив и разложить его поверх папки программы. Порядок — от дешёвого отказа к
      необратимому шагу: сумма → распаковка во временную папку → состав → версия → и только
      потом замена файлов. Любой отказ до последнего шага не трогает папку программы вовсе.
    #>
    param(
        [Parameter(Mandatory)][string]$Архив,
        [Parameter(Mandatory)][string]$ТекстСумм,
        [Parameter(Mandatory)][string]$Версия,
        [Parameter(Mandatory)][string]$ПапкаПрограммы
    )
    $имя = Split-Path -Leaf $Архив
    $ожидаемая = Ожидаемая-Сумма $ТекстСумм $имя
    if (-not $ожидаемая) { throw "в контрольных суммах нет строки для $имя" }
    $фактическая = (Get-FileHash -LiteralPath $Архив -Algorithm SHA256).Hash
    if ($фактическая -ne $ожидаемая) { throw 'контрольная сумма не сошлась: загрузка испорчена или оборвана' }

    $распаковка = Join-Path (Split-Path -Parent $Архив) ('x-' + [guid]::NewGuid().ToString('N'))
    Expand-Archive -LiteralPath $Архив -DestinationPath $распаковка -Force
    $найдено = Get-ChildItem -LiteralPath $распаковка -Recurse -Filter 'SteamDeck-KVM.ps1' | Select-Object -First 1
    if (-not $найдено) { throw 'в архиве нет SteamDeck-KVM.ps1 — это не архив приложения для ПК' }
    $корень = $найдено.DirectoryName
    $файлВерсии = Join-Path $корень 'VERSION'
    if (-not (Test-Path -LiteralPath $файлВерсии)) { throw 'в архиве нет файла VERSION' }
    $версияАрхива = (Get-Content -LiteralPath $файлВерсии -Raw).Trim()
    if ($версияАрхива -ne $Версия) { throw "в архиве версия $версияАрхива, а ожидалась $Версия" }

    # Файлы программы заменяются на месте: работающий скрипт уже прочитан в память, а данные
    # приложения лежат в %LOCALAPPDATA% и копированием не задеваются.
    Copy-Item -Path (Join-Path $корень '*') -Destination $ПапкаПрограммы -Recurse -Force
    Remove-Item -LiteralPath $распаковка -Recurse -Force -ErrorAction SilentlyContinue
    return $корень
}
