# НАЗНАЧЕНИЕ ЭТОГО МОДУЛЯ — Обновление приложения ПК из выпусков GitHub: выбор выпуска, сверка суммы установщика
#
# ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ — приложение держит окно и сервер, и проверить в нём обновление можно
# было бы только живым запуском, который трогает работающий сервер и ярлык на рабочем столе.
# Здесь только решения без окна и без сети: какой выпуск взять и сошлась ли сумма скачанного
# установщика; файлы раскладывает сам установщик, запущенный тихо. Их проверяет tests\apps\test_pc_app_update.py в памяти. Загрузку и очередность шагов
# ведёт само приложение — там, где у него таймер.
#
# ЧЕГО СВЕРКА СУММЫ НЕ ДОКАЗЫВАЕТ — она ловит оборванную и испорченную загрузку; от подмены
# выпуска владельцем учётной записи не защищает: сумма лежит в том же выпуске.

function Разобрать-Версию([string]$Текст) {
    if ($Текст -match '^v?(\d+)\.(\d+)\.(\d+)') {
        return [version]("{0}.{1}.{2}" -f $Matches[1], $Matches[2], $Matches[3])
    }
    return $null
}

function Выбрать-Обновление($Выпуск, [string]$ТекущаяВерсия) {
    <#
      Выпуск новее текущей версии с установщиком для ПК и его контрольной суммой — либо $null.
      Сумму считает сам GitHub и отдаёт полем `digest` файла выпуска («sha256:…»).
      Причина пропуска возвращается полем, а не пишется в журнал отсюда: журнал ведёт приложение.
    #>
    $новая = Разобрать-Версию $Выпуск.tag_name
    $текущая = Разобрать-Версию $ТекущаяВерсия
    if (-not $новая -or -not $текущая -or $новая -le $текущая) { return $null }
    $архив = @($Выпуск.assets | Where-Object { $_.name -like 'SteamDeck-KVM-*-windows-x64-setup.exe' })[0]
    $сумма = if ($архив -and "$($архив.digest)" -match '^sha256:([0-9a-fA-F]{64})$') { $Matches[1].ToUpperInvariant() } else { $null }
    if (-not $архив -or -not $сумма) {
        return @{ Пропуск = ("выпуск {0} без установщика для ПК или без его контрольной суммы" -f $Выпуск.tag_name) }
    }
    $заметка = @(($Выпуск.body -split "`n") | Where-Object { $_.Trim() })[0]
    $заметка = if ($заметка) { $заметка.Trim().TrimStart('#', '-', ' ').Trim() } else { '' }
    return @{ Версия = "$новая"; Архив = $архив; Сумма = $сумма; Заметка = $заметка }
}

function Проверить-Установщик {
    <#
      Сверить скачанный установщик с суммой, которую GitHub отдал в описании выпуска. Возвращает путь
      к нему либо бросает исключение с причиной; установщик с несошедшейся суммой не запускается.
    #>
    param(
        [Parameter(Mandatory)][string]$Установщик,
        [Parameter(Mandatory)][AllowEmptyString()][string]$Сумма
    )
    $имя = Split-Path -Leaf $Установщик
    if ($Сумма -notmatch '^[0-9a-fA-F]{64}$') { throw "у $имя нет контрольной суммы — установщик не запускается" }
    $фактическая = (Get-FileHash -LiteralPath $Установщик -Algorithm SHA256).Hash
    if ($фактическая -ne $Сумма.ToUpperInvariant()) { throw 'контрольная сумма не сошлась: загрузка испорчена или оборвана' }
    $начало = [System.IO.File]::ReadAllBytes($Установщик)[0..1]
    if ($начало[0] -ne 0x4D -or $начало[1] -ne 0x5A) { throw "$имя — не исполняемый файл Windows" }
    return $Установщик
}
